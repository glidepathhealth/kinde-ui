// Regenerates kindeSrc/assets/brand-assets.ts from the official SVGs in
// kindeSrc/assets/brand/. Kinde does not host static assets, so the artwork has
// to travel with the page as base64 data URIs. Encoding the files verbatim also
// satisfies the brand guide's rule that the logo and Glide Path pattern are only
// ever composited from the official files, never redrawn.
//
//   node scripts/build-brand-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dataUri = (rel) =>
  "data:image/svg+xml;base64," +
  readFileSync(resolve(root, "kindeSrc/assets/brand", rel)).toString("base64");

const assets = {
  logoHorizontalInverse: "logo/logo-horizontal-inverse.svg",
  logoHorizontalFullColor: "logo/logo-horizontal-full-color.svg",
  brandGradient: "pattern/gradient-digital.svg",
  glidePathWhite: "pattern/glide-path-white.svg",
};

const body = Object.entries(assets)
  .map(([name, rel]) => `// ${rel}\nexport const ${name} = "${dataUri(rel)}";`)
  .join("\n\n");

writeFileSync(
  resolve(root, "kindeSrc/assets/brand-assets.ts"),
  `// GENERATED by scripts/build-brand-assets.mjs — do not edit by hand.\n` +
    `// Source files live in kindeSrc/assets/brand/.\n\n${body}\n`,
);
console.log("wrote kindeSrc/assets/brand-assets.ts");
